"""Builds the app's school-paper data from the transcriptions in data/.

Each data/<subject>_<year>_<school>.py holds one paper (PAPER, optional PASSAGES, Q list).
Figures are cropped from the source PDFs into source_papers/<year>/figs/ and the combined data is written to
source_papers/p5_past_papers.js (loaded by App Launch.html) plus a flat JSON for "Import Questions from File".
Run: python3 build.py
"""
import fitz, json, importlib.util, glob, os, re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))  # .../source_papers
DATA = os.path.join(os.path.dirname(os.path.abspath(__file__)), "data")
SUBJECT_ORDER = {"Math": 0, "Science": 1, "English": 2}

papers, flat, skipped = [], [], []
first_crop = {}

def crop(pdf, year, key, name, page, box, dpi=170):
    figdir = f"{ROOT}/{year}/figs"
    os.makedirs(figdir, exist_ok=True)
    d = fitz.open(pdf); p = d[page-1]; s = p.rect.width/910   # boxes are in px of a 910-px-wide page render
    r = fitz.Rect(box[0]*s, box[1]*s, box[2]*s, box[3]*s) & p.rect
    fn = f"{key}-{name}.png"
    p.get_pixmap(dpi=dpi, clip=r, colorspace=fitz.csGRAY).save(f"{figdir}/{fn}")
    return f"source_papers/{year}/figs/{fn}"

mods = []
for path in sorted(glob.glob(f"{DATA}/*.py")):
    name = os.path.basename(path)[:-3]
    spec = importlib.util.spec_from_file_location(name, path); m = importlib.util.module_from_spec(spec); spec.loader.exec_module(m)
    mods.append(m)
mods.sort(key=lambda m: (-m.PAPER["year"], SUBJECT_ORDER.get(m.PAPER["subject"], 9), m.PAPER["school"]))

for m in mods:
    P = m.PAPER; pdf = f"{ROOT}/{P['pdf']}"; key = P["key"]; year = P["year"]
    passages = {}
    for pid, pv in getattr(m, "PASSAGES", {}).items():
        if isinstance(pv, str): passages[pid] = {"id": f"{key}-{pid}", "text": pv, "images": []}
        else: passages[pid] = {"id": f"{key}-{pid}", "text": pv.get("text",""),
                               "images": [crop(pdf, year, key, f"passage-{pid}-{i+1}", b[0], list(b[1:]), dpi=200) for i,b in enumerate(pv.get("img", []))]}
    uses = {}
    for q in m.Q:
        f = q.get("fig") or []
        for t in ([f] if isinstance(f, tuple) else f): uses[tuple(t)] = uses.get(tuple(t), 0) + 1
    qs = []
    for q in m.Q:
        if "skip" in q: skipped.append(f"{P['title']} {q['n']}: {q['skip']}"); continue
        slug = re.sub(r"[^a-z0-9]+","-",q["n"].lower()).strip("-")
        figs = q.get("fig") or []
        if isinstance(figs, tuple): figs = [figs]
        images = []
        for i, f in enumerate(figs):
            shared = uses.get(tuple(f), 0) > 1
            path = crop(pdf, year, key, slug + (f"-{i+1}" if len(figs) > 1 else ""), f[0], f[1:], dpi=300 if shared else 170)
            # The same crop used by several questions (e.g. a poster) points at one file, so print shows it once.
            images.append(first_crop.setdefault((key, tuple(f)), path))
        sol = q.get("solution","")
        text = q["text"]
        if q.get("note"):
            sol = (sol + "  " if sol else "") + "Note: " + q["note"]
            text += "\n(Part of the original question is not included here.)"
            skipped.append(f"{P['title']} {q['n']} (part): {q['note']}")
        out = {
            "subject": P["subject"], "topic": q["topic"], "type": q["type"], "difficulty": "Medium",
            "text": text, "options": q.get("options", []), "answer": q["answer"], "solution": sol,
            "images": images,
            "source": {"school": P["school"], "year": year, "exam": P["exam"], "paper": P["title"], "paperKey": key, "qno": q["n"], "marks": q.get("marks",1)},
        }
        if q.get("accept"): out["accept"] = q["accept"]
        shared_imgs = [first_crop[(key, tuple(f))] for f in figs if uses.get(tuple(f), 0) > 1]
        if shared_imgs: out["sharedImages"] = shared_imgs
        if q.get("passage"): out["passage"] = passages[q["passage"]]
        assert q["type"] != "MCQ" or out["answer"] in out["options"], (key, q["n"])
        qs.append(out)
    papers.append({"key": key, "title": P["title"], "subject": P["subject"], "school": P["school"], "year": year, "exam": P["exam"],
                   "sourcePdf": f"source_papers/{P['pdf']}", "sourceSite": P.get("site", "testpapersfree.com"), "questions": qs})
    flat += qs

js = "// Generated by source_papers/build/build.py from free P5 school papers (see source_papers/<year>/). Loaded by App Launch.html.\nwindow.P5_PAST_PAPERS = " + json.dumps(papers, ensure_ascii=False, indent=1) + ";\n"
open(f"{ROOT}/p5_past_papers.js","w").write(js)
json.dump(flat, open(f"{ROOT}/p5_past_papers_questions.json","w"), ensure_ascii=False, indent=1)
open(f"{ROOT}/SKIPPED.txt","w").write("\n".join(skipped)+"\n")
for p in papers:
    c = {}
    for q in p["questions"]: c[q["type"]] = c.get(q["type"],0)+1
    print(p["year"], p["title"], len(p["questions"]), c)
print("total", len(papers), "papers,", len(flat), "questions; skipped", len(skipped))
